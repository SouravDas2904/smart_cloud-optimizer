"use client";

import { Download, FileCode2, FileSpreadsheet, Printer, Terminal } from "lucide-react";
import { useApp } from "../providers";
import { Loading, PageTitle } from "@/components/ui";
import { totals } from "@/lib/engine";
import { ACTION_LABEL, inr } from "@/lib/format";
import type { Recommendation } from "@/lib/types";

function download(name: string, text: string, type = "text/plain") {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.click();
  URL.revokeObjectURL(url);
}

const csvCell = (v: unknown) => `"${String(v ?? "").replace(/"/g, '""')}"`;

function toCsv(recs: Recommendation[]) {
  const head = ["id", "resource", "resource_id", "env", "region", "team", "action", "current_plan", "target_plan", "monthly_saving_inr", "risk", "confidence", "reason"];
  return [head.join(","), ...recs.map((r) => [r.id, r.resource_name, r.resource_id, r.env, r.region, r.team, r.action, r.current_plan, r.target_plan, r.saving, r.risk, r.confidence, r.reason].map(csvCell).join(","))].join("\n");
}

function toTerraform(recs: Recommendation[]) {
  const resize = recs.filter((r) => r.action === "resize" || r.action === "upsize");
  const lines = [
    "# Generated by SmartCloud Optimizer. REVIEW BEFORE APPLYING.",
    "# Plan changes keyed by VM name. Reference from your instance resources, e.g.",
    "#   plan = lookup(local.rightsizing, each.key, { to = each.value.plan }).to",
    "locals {",
    "  rightsizing = {",
    ...resize.map((r) => `    "${r.resource_name}" = { from = "${r.current_plan}", to = "${r.target_plan}" } # ${r.saving >= 0 ? "saves" : "costs"} ₹${Math.abs(r.saving)}/mo, ${r.risk} risk`),
    "  }",
    "",
    "  # Off-hours schedules (stop 20:00, start 08:00 IST, off weekends)",
    "  offhours_schedule = [",
    ...recs.filter((r) => r.action === "schedule").map((r) => `    "${r.resource_name}",`),
    "  ]",
    "}",
  ];
  return lines.join("\n");
}

function toShell(recs: Recommendation[]) {
  const by = (a: string) => recs.filter((r) => r.action === a);
  return [
    "#!/usr/bin/env bash",
    "# Generated by SmartCloud Optimizer. REVIEW BEFORE RUNNING.",
    "# Set CLOUD_CLI to your provider's CLI (commands below are illustrative).",
    "set -euo pipefail",
    'CLOUD_CLI="${CLOUD_CLI:-echo cloud}"',
    "",
    "# --- stop idle VMs ---",
    ...by("stop").map((r) => `$CLOUD_CLI server stop --id ${r.resource_id}   # ${r.resource_name}, saves ₹${r.saving}/mo`),
    "",
    "# --- snapshot, then delete orphaned volumes ---",
    ...by("delete_volume").flatMap((r) => [`$CLOUD_CLI volume snapshot --id ${r.resource_id} --name pre-delete-${r.resource_id}`, `$CLOUD_CLI volume delete --id ${r.resource_id}   # ${r.resource_name}, saves ₹${r.saving}/mo`]),
    "",
    "# --- release unused public IPs ---",
    ...by("release_ip").map((r) => `$CLOUD_CLI ip release --id ${r.resource_id}   # ${r.resource_name}`),
    "",
    "# --- off-hours schedule: add to crontab (IST) ---",
    ...by("schedule").flatMap((r) => [
      `# ${r.resource_name}: saves ₹${r.saving}/mo`,
      `#   0 20 * * 1-5  $CLOUD_CLI server stop  --id ${r.resource_id}`,
      `#   0 8  * * 1-5  $CLOUD_CLI server start --id ${r.resource_id}`,
    ]),
  ].join("\n");
}

export default function Report() {
  const { data, accepted } = useApp();
  if (!data) return <Loading />;
  const t = totals(data.resources, data.recs, accepted);
  const acc = data.recs.filter((r) => accepted[r.id]).sort((a, b) => b.saving - a.saving);
  const stamp = data.summary.generated_at.slice(0, 10);

  return (
    <div className="space-y-5">
      <div className="no-print">
        <PageTitle title="Report & export" sub="Everything you have accepted, as a printable report for finance or as files your engineers can review and apply." />
        <div className="flex flex-wrap gap-2">
          <button className="btn-primary" onClick={() => window.print()}><Printer size={14} /> Print / save as PDF</button>
          <button className="btn-ghost" onClick={() => download(`smartcloud-recommendations-${stamp}.csv`, toCsv(acc), "text/csv")}><FileSpreadsheet size={14} /> CSV</button>
          <button className="btn-ghost" onClick={() => download(`rightsizing-${stamp}.tf`, toTerraform(acc))}><FileCode2 size={14} /> Terraform</button>
          <button className="btn-ghost" onClick={() => download(`cleanup-${stamp}.sh`, toShell(acc))}><Terminal size={14} /> Shell script</button>
          <button className="btn-ghost" onClick={() => download(`smartcloud-${stamp}.json`, JSON.stringify(acc, null, 2), "application/json")}><Download size={14} /> JSON</button>
        </div>
      </div>

      <div className="card p-6 md:p-8">
        <div className="flex flex-wrap items-start justify-between gap-3 border-b border-slate-200 pb-4">
          <div>
            <div className="text-xs font-semibold uppercase tracking-wide text-brand-600">SmartCloud Optimizer · Cost optimisation report</div>
            <h1 className="mt-1 text-2xl font-semibold text-slate-900">Save {inr(t.saving)} per month ({((t.saving / t.before) * 100).toFixed(1)}%)</h1>
            <p className="text-sm text-slate-500">Data window: 30 days ending {stamp} · {data.summary.n_resources} resources analysed · prices illustrative (see assumptions)</p>
          </div>
          <div className="text-right text-sm">
            <div>Current: <b>{inr(t.before)}</b>/mo</div>
            <div>After: <b className="text-save-700">{inr(t.after)}</b>/mo</div>
            <div>Annual: <b className="text-save-700">{inr(t.saving * 12)}</b></div>
          </div>
        </div>

        <h2 className="mt-5 font-semibold text-slate-900">Summary by action</h2>
        <table className="mt-2 w-full text-sm">
          <tbody>
            {Object.entries(t.byAction).sort((a, b) => b[1] - a[1]).map(([a, v]) => (
              <tr key={a} className="border-t border-slate-100"><td className="py-1.5">{ACTION_LABEL[a]}</td><td className="text-right">{acc.filter((r) => r.action === a).length} items</td><td className="text-right font-medium tabular-nums">{inr(v)}/mo</td></tr>
            ))}
          </tbody>
        </table>

        <h2 className="mt-6 font-semibold text-slate-900">Accepted recommendations ({acc.length})</h2>
        <table className="mt-2 w-full text-xs">
          <thead><tr className="text-left uppercase text-slate-500"><th className="py-1">Resource</th><th>Team</th><th>Action</th><th>Change</th><th>Risk</th><th className="text-right">₹/mo</th></tr></thead>
          <tbody>
            {acc.map((r) => (
              <tr key={r.id} className="border-t border-slate-100 align-top">
                <td className="py-1.5 pr-2"><b>{r.resource_name}</b><div className="text-slate-500">{r.reason}</div></td>
                <td className="pr-2">{r.team}</td><td className="pr-2">{ACTION_LABEL[r.action]}</td>
                <td className="mono pr-2">{r.current_plan && r.target_plan && r.current_plan !== r.target_plan ? `${r.current_plan}→${r.target_plan}` : "—"}</td>
                <td className="pr-2">{r.risk}</td><td className="text-right tabular-nums">{inr(r.saving)}</td>
              </tr>
            ))}
          </tbody>
        </table>
        <p className="mt-6 text-xs text-slate-400">Sizing rule: target plan keeps p99 CPU ≤ 70% and p99 memory ≤ 75%. Production idle VMs are flagged for owner review, never stopped automatically. Volumes are snapshotted before deletion.</p>
      </div>
    </div>
  );
}
